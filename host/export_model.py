"""Export the decision rule of analysis/classify.py to the instrument, as firmware/src/model.h.

From the project root:
    python -I firmware/host/export_model.py                          data/potentiostat -> firmware/src/model.h
    python -I firmware/host/export_model.py --data DIR --out FILE    another data set, e.g. to test

The rule is fitted exactly as classify.py fits it inside each training fold (scaling, principal
components, logistic regression, novelty limit; the peak-rule limit from the blanks), but once, on
the whole phase-B data set. classify.py's leave-one-day-out results describe how this procedure
performs; this file is the procedure applied to all the data, for use on the instrument. Nothing is
tuned here: the settings are read from classify.py.

Checks, before anything is written:
  - every scan carries the same "# config:" line: the model is tied to that configuration, and the
    firmware refuses it in any other (its CRC-32 goes into model.h);
  - every scan comes from the esp32 instrument, and none is an invented curve;
  - the fitted model reproduces classify.fit_predict on the same data;
  - the device formula (softmax of the scores) reproduces LogisticRegression.predict_proba.
Then, if g++ is found, firmware/src/rule.cpp is compiled on this computer with the new model and run
on every scan and every preparation: its results must match classify.py's. model.h also embeds three
of the scans with their expected results, which the firmware checks at power-up ("selftest").
The device model can only come from data/potentiostat.
"""
import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler

HERE = Path(__file__).resolve().parent
FW = HERE.parent
ROOT = FW.parent
sys.path.insert(0, str(ROOT / "analysis"))
import classify  # noqa: E402

DEVICE_MODEL = FW / "src" / "model.h"
REAL_DATA = ROOT / "data" / "potentiostat"
FIRMWARE_CLASSES = ["blank", "propineb", "other"]  # order of the Verdict enum in rule.h
CONFIG_LINE = re.compile(r"^# config: (\S+), crc32 0x([0-9A-Fa-f]{8})\s*$")


def header_of(path):
    """Comment lines before the column line."""
    lines = []
    with open(path, encoding="ascii", errors="replace") as f:
        for line in f:
            if not line.startswith("#"):
                break
            lines.append(line.rstrip("\r\n"))
    return lines


def fit(X, y):
    """The steps of classify.fit_predict, keeping the fitted objects."""
    scaler = StandardScaler().fit(X)
    Z = scaler.transform(X)
    pca = PCA(n_components=min(classify.N_COMPONENTS, len(X) - 1, X.shape[1])).fit(Z)
    T = pca.transform(Z)
    model = LogisticRegression(max_iter=5000).fit(T, y)
    resid = np.sqrt(((Z - pca.inverse_transform(T)) ** 2).sum(axis=1))
    limit = classify.NOVELTY_FACTOR * np.percentile(resid, 99)
    return scaler, pca, model, limit


def apply(scaler, pca, coef, intercept, limit, X):
    """The arithmetic of rule.cpp, in float64."""
    Z = (X - scaler.mean_) / scaler.scale_
    T = (Z - pca.mean_) @ pca.components_.T
    resid = np.sqrt(((Z - (T @ pca.components_ + pca.mean_)) ** 2).sum(axis=1))
    s = T @ coef.T + intercept
    s -= s.max(axis=1, keepdims=True)
    p = np.exp(s) / np.exp(s).sum(axis=1, keepdims=True)
    return p, resid, resid > limit


def combine(p, novel):
    """classify.evaluate, for one preparation: verdict index (3 = indeterminate) and mean p."""
    m = p.mean(axis=0)
    v = int(np.argmax(m))
    if m.max() < classify.P_MIN or novel.any():
        v = 3
    return v, m


def cfloat(v):
    v = float(np.float32(v))
    if not np.isfinite(v):
        raise SystemExit("a value of the model is not finite")
    s = f"{v:.9g}"
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def carray(values, per_line=6, indent="  "):
    vals = [cfloat(v) for v in np.asarray(values, dtype=float).ravel()]
    return ",\n".join(indent + ", ".join(vals[k:k + per_line]) for k in range(0, len(vals), per_line))


def write_header(path, info):
    nf, nc = info["X_mean"].size, info["coef"].shape[1]
    o = []
    o.append("// model.h -- GENERATED by firmware/host/export_model.py; do not edit.")
    o.append(f"// Data: {info['data']}, {info['n_scans']} phase-B scans of {info['n_preps']} preparations, "
             f"days {info['days']}.")
    o.append("// The decision rule of analysis/classify.py (scaling, principal components, logistic")
    o.append("// regression, P_MIN, novelty limit; peak-rule limit from the blanks), fitted once on all of it.")
    o.append("#pragma once")
    o.append("#include <stdint.h>")
    o.append("#define MODEL_PRESENT 1")
    o.append(f'#define MODEL_NAME "{info["name"]}"')
    o.append(f"#define MODEL_CONFIG_CRC 0x{info['crc']:08X}u")
    o.append(f"#define MODEL_N_GRID {classify.GRID.size}")
    o.append(f"#define MODEL_N_FEAT {nf}")
    o.append(f"#define MODEL_N_COMP {nc}")
    o.append("#define MODEL_N_CLASS 3")
    o.append(f"#define MODEL_PEAK_K0 {info['k0']}")
    o.append(f"#define MODEL_PEAK_K1 {info['k1']}")
    o.append(f"#define MODEL_P_MIN {cfloat(classify.P_MIN)}")
    o.append(f"#define MODEL_NOVELTY_LIMIT {cfloat(info['limit'])}")
    o.append(f"#define MODEL_PEAK_LIMIT_A {cfloat(info['peak_limit'])}")
    o.append(f"#define MODEL_N_TRAIN_SCANS {info['n_scans']}")
    o.append(f"#define MODEL_N_TRAIN_PREPS {info['n_preps']}")
    o.append("static const float MODEL_GRID[MODEL_N_GRID] = {\n" + carray(classify.GRID) + "};")
    o.append("static const float MODEL_X_MEAN[MODEL_N_FEAT] = {\n" + carray(info["X_mean"]) + "};")
    o.append("static const float MODEL_X_SCALE[MODEL_N_FEAT] = {\n" + carray(info["X_scale"]) + "};")
    o.append("static const float MODEL_PCA_MEAN[MODEL_N_FEAT] = {\n" + carray(info["pca_mean"]) + "};")
    rows = ",\n".join("  {\n" + carray(r, indent="    ") + "}" for r in info["comp"])
    o.append("static const float MODEL_PCA_COMP[MODEL_N_COMP][MODEL_N_FEAT] = {\n" + rows + "};")
    rows = ",\n".join("  {" + ", ".join(cfloat(v) for v in r) + "}" for r in info["coef"])
    o.append(f"// rows in the order {', '.join(FIRMWARE_CLASSES)}")
    o.append("static const float MODEL_COEF[MODEL_N_CLASS][MODEL_N_COMP] = {\n" + rows + "};")
    o.append("static const float MODEL_INTERCEPT[MODEL_N_CLASS] = {"
             + ", ".join(cfloat(v) for v in info["intercept"]) + "};")
    t = info["tests"]
    o.append("// self-test: scans as recorded, and what the fitted model gives them")
    o.append(f"#define MODEL_N_TEST {len(t)}")
    o.append("static const char* const MODEL_TEST_FILE[MODEL_N_TEST] = {"
             + ", ".join(f'"{x["file"]}"' for x in t) + "};")
    o.append("static const int MODEL_TEST_LEN[MODEL_N_TEST] = {" + ", ".join(str(len(x["e"])) for x in t) + "};")
    o.append("static const float MODEL_TEST_E[] = {\n" + carray(np.concatenate([x["e"] for x in t])) + "};")
    o.append("static const float MODEL_TEST_I[] = {\n" + carray(np.concatenate([x["i"] for x in t])) + "};")
    o.append("static const float MODEL_TEST_P[MODEL_N_TEST][3] = {"
             + ", ".join("{" + ", ".join(cfloat(v) for v in x["p"]) + "}" for x in t) + "};")
    o.append("static const float MODEL_TEST_RESID[MODEL_N_TEST] = {" + ", ".join(cfloat(x["resid"]) for x in t) + "};")
    o.append("static const float MODEL_TEST_PEAK[MODEL_N_TEST] = {" + ", ".join(cfloat(x["peak"]) for x in t) + "};")
    path.write_text("\n".join(o) + "\n", encoding="ascii", newline="\n")


def host_check(model_h, man, data_dir, p, resid, novel):
    """Compile rule.cpp with the new model on this computer and compare with classify.py."""
    gxx = shutil.which("g++")
    if not gxx:
        print("host check: g++ not found, skipped; run 'selftest' on the instrument")
        return True
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        for f in ("rule.cpp", "rule.h"):
            shutil.copy(FW / "src" / f, td / f)
        shutil.copy(model_h, td / "model.h")  # next to rule.cpp, so that it wins over src/model.h
        exe = td / "rule_check.exe"
        build = subprocess.run([gxx, "-std=c++17", "-O2", "-Wall", f"-I{td}", str(HERE / "rule_check.cpp"),
                                str(td / "rule.cpp"), "-o", str(exe)], capture_output=True, text=True)
        if build.returncode:
            raise SystemExit("host check: rule.cpp does not compile:\n" + build.stderr)
        groups = list(man.groupby("preparation_id", sort=False).groups.values())
        lines = [str(len(groups))]
        for rows in groups:
            lines.append(str(len(rows)))
            for r in rows:
                df = pd.read_csv(data_dir / "scans" / man.loc[r, "file"], comment="#")
                lines.append(str(len(df)))
                lines += [f"{a:.9g} {b:.9g}" for a, b in zip(df["E_V"], df["I_A"])]
        run = subprocess.run([str(exe)], input="\n".join(lines) + "\n", capture_output=True, text=True)
        if run.returncode:
            raise SystemExit("host check: rule_check failed\n" + run.stderr)
    out = run.stdout.splitlines()
    scans = [l.split() for l in out if l.startswith("scan ")]
    samples = [l.split() for l in out if l.startswith("sample ")]
    order = [r for rows in groups for r in rows]
    bad = [man.loc[r, "file"] for r, s in zip(order, scans) if s[1] != "ok"]
    if bad:
        raise SystemExit(f"host check: rule.cpp could not read {bad}")
    c = np.array([[float(v) for v in s[2:8]] for s in scans])
    dp = np.abs(c[:, 0:3] - p[order]).max()
    dr = (np.abs(c[:, 3] - resid[order]) / np.maximum(resid[order], 1e-12)).max()
    peak = man["peak_A"].to_numpy()[order]
    dk_abs = np.abs(c[:, 5] - peak)
    dk_ok = (dk_abs < 1e-4 * np.abs(peak) + 1e-10).all()  # 1e-4 relative + 0.1 nA, as the self-test
    dk = dk_abs.max()
    dn = int((c[:, 4].astype(bool) != novel[order]).sum())
    agree, total = 0, len(groups)
    for rows, s in zip(groups, samples):
        v, _ = combine(p[list(rows)], novel[list(rows)])
        agree += int(int(s[1]) == v)
    st = [l for l in out if l.startswith("selftest ")]
    st_fail = int(out[-1].split()[1])
    print(f"host check (g++): {len(scans)} scans, max |dp| {dp:.1e}, residual rel. {dr:.1e}, "
          f"peak {dk:.1e} A, novelty flags differing {dn}; verdicts agree for {agree}/{total} "
          f"preparations; self-test {len(st) - st_fail}/{len(st)} passed")
    return dp < 1e-4 and dr < 1e-4 and dk_ok and dn == 0 and agree == total and st_fail == 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--data", type=Path, default=REAL_DATA, help="data folder with manifest.csv and scans/")
    ap.add_argument("--out", type=Path, default=DEVICE_MODEL, help="header to write")
    a = ap.parse_args()
    data_dir, out = a.data.resolve(), a.out.resolve()
    to_device = out == DEVICE_MODEL.resolve()
    if to_device and data_dir != REAL_DATA.resolve():
        raise SystemExit(f"the device model comes from {REAL_DATA.relative_to(ROOT)} only; use --out for a test")
    if classify.CLASSES != FIRMWARE_CLASSES:
        raise SystemExit(f"classify.CLASSES is {classify.CLASSES}; the firmware expects {FIRMWARE_CLASSES}")

    man, X, n_rejected = classify.load(data_dir)
    y = man["class"].to_numpy()
    if set(y) != set(FIRMWARE_CLASSES):
        raise SystemExit(f"the data set must hold the three classes; it holds {sorted(set(y))}")

    # one configuration, one instrument, real curves
    configs = set()
    for f in man["file"]:
        h = header_of(data_dir / "scans" / f)
        if any("INVENTED" in line for line in h) and to_device:
            raise SystemExit(f"{f} is an invented curve")
        m = [CONFIG_LINE.match(line) for line in h]
        m = [x for x in m if x]
        if not m:
            raise SystemExit(f"{f} has no '# config:' line: it was not recorded by the firmware")
        configs.add((m[0].group(1), int(m[0].group(2), 16)))
    if len(configs) != 1:
        found = ", ".join(f"{n} 0x{c:08X}" for n, c in sorted(configs))
        raise SystemExit(f"the scans come from more than one configuration: {found}")
    (config_name, crc), = configs
    instruments = set(man["instrument"])
    if instruments != {"esp32"}:
        raise SystemExit(f"the scans must all come from the esp32 instrument; found {sorted(instruments)}")

    # fit, and check against classify.py
    scaler, pca, model, limit = fit(X, y)
    order = [list(model.classes_).index(c) for c in FIRMWARE_CLASSES]
    coef, intercept = model.coef_[order], model.intercept_[order]
    p, resid, novel = apply(scaler, pca, coef, intercept, limit, X)
    p_cls, novel_cls = classify.fit_predict(X, y, X)
    if not (np.allclose(p, p_cls, atol=1e-9) and (novel == novel_cls).all()):
        raise SystemExit("the fitted model does not reproduce classify.fit_predict")
    if not np.allclose(p, model.predict_proba(pca.transform(scaler.transform(X)))[:, order], atol=1e-9):
        raise SystemExit("softmax of the scores does not reproduce predict_proba")

    window = np.where((classify.GRID >= classify.PEAK_WINDOW[0]) & (classify.GRID <= classify.PEAK_WINDOW[1]))[0]
    if not (window.size and (np.diff(window) == 1).all()):
        raise SystemExit("the peak window is not a run of grid points")
    blanks = man.loc[y == "blank", "peak_A"]
    peak_limit = blanks.mean() + classify.PEAK_SIGMAS * blanks.std(ddof=1)

    tests = []
    for c in FIRMWARE_CLASSES:
        r = int(np.where(y == c)[0][0])
        df = pd.read_csv(data_dir / "scans" / man.loc[r, "file"], comment="#")
        tests.append({"file": man.loc[r, "file"], "e": df["E_V"].to_numpy(float), "i": df["I_A"].to_numpy(float),
                      "p": p[r], "resid": resid[r], "peak": man.loc[r, "peak_A"]})

    days = sorted(set(man["date"]))
    info = {"data": data_dir.relative_to(ROOT) if ROOT in data_dir.parents else data_dir,
            "n_scans": len(man), "n_preps": man["preparation_id"].nunique(), "days": ", ".join(days),
            "name": f"{config_name} {days[-1]}"[:21], "crc": crc, "k0": int(window[0]), "k1": int(window[-1]),
            "limit": limit, "peak_limit": peak_limit, "X_mean": scaler.mean_, "X_scale": scaler.scale_,
            "pca_mean": pca.mean_, "comp": pca.components_, "coef": coef, "intercept": intercept, "tests": tests}

    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td) / "model.h"
        write_header(tmp, info)
        if not host_check(tmp, man, data_dir, p, resid, novel):
            raise SystemExit("host check FAILED: model.h not written")
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(tmp, out)

    v = [combine(p[list(rows)], novel[list(rows)])[0] for rows in man.groupby("preparation_id", sort=False).groups.values()]
    print(f"model '{info['name']}' (config crc32 0x{crc:08X}): {len(man)} scans, {info['n_preps']} preparations, "
          f"{n_rejected} scans rejected or not filled in; {pca.n_components_} components; novelty limit {limit:.3g}; "
          f"peak blank limit {peak_limit:.3g} A; on its own training data {v.count(3)} preparations indeterminate")
    print(f"written: {out}")
    if to_device:
        print("rebuild and upload the firmware; at power-up it runs the self-test (also: 'selftest')")


if __name__ == "__main__":
    main()
